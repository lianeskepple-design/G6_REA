{
    if (id == NULL) {
        return NULL;
    }

    for (size_t i = 0; i < g6_eq_preset_count; ++i) {
        if (strcmp(g6_eq_presets[i].id, id) == 0) {
            return &g6_eq_presets[i];
        }
    }

    return NULL;
}
